        private void btnAccederActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnAccederActionPerformed
                // TODO add your handling code here:
                try {

                        nombre = txtUsu.getText().trim();
                        pass = txtPass.getText().trim();

                        Usuario usuario = ServicioUsuario.buscarUsuarioPorNombre(nombre);

                        if (usuario == null) {

                                JOptionPane.showMessageDialog(this, "Ese usuario no existe");

                        } else if (!usuario.getPass().equals(pass)) {

                                JOptionPane.showMessageDialog(this, "Contraseña incorrecta");

                        } else {

                                CuentaApp cuentaApp = ServicioCuentaApp.buscarCuentaUsuario(
                                                usuario.getCodUsuarios());

                                Cuenta u = new Cuenta(
                                                this, true, usuario, cuentaApp);

                                u.setLocationRelativeTo(null);
                                u.setVisible(true);
                                // cierro pantalla para al entrar a cuentas
                                this.dispose();
                        }

                } catch (IllegalArgumentException e) {

                        JOptionPane.showMessageDialog(this,
                                        e.getMessage());

                } catch (Exception e) {

                        JOptionPane.showMessageDialog(this,
                                        "Ha ocurrido un error inesperado PP ");
                }

        }// GEN-LAST:event_btnAccederActionPerformed

