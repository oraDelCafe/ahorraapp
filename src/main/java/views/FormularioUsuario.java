    private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnCrearActionPerformed
        // TODO add your handling code here:
        try {

            String nombre = tctNombre.getText().trim();
            String ape1 = txtApe1.getText().trim();
            String ape2 = txtApe2.getText().trim();
            String dni = txtDni.getText().trim();
            String direccion = txtDir.getText().trim();
            String telefono = txtTele.getText().trim();
            String email = txtEmail1.getText().trim();
            String pass = txtPass.getText().trim();
            String cuentaVinculada = txtCuentaVExt.getText().trim();

            if (nombre.isEmpty() || ape1.isEmpty() || ape2.isEmpty()
                    || dni.isEmpty() || direccion.isEmpty() || telefono.isEmpty()
                    || email.isEmpty() || pass.isEmpty()
                    || cuentaVinculada.isEmpty()) {

                throw new IllegalArgumentException("Faltan campos por rellenar");

            }

            Usuario usuario = new Usuario(nombre, ape1, ape2, pass, email, dni, direccion, telefono);

            ServicioUsuario.crearUsuario(usuario);

            CuentaApp cuenta = new CuentaApp(usuario, 0.0, LocalDate.now(), cuentaVinculada);

            ServicioCuentaApp.crearCuentaApp(cuenta);

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Usuario creado correctamente");

            this.dispose();

        } catch (Exception e) {

            javax.swing.JOptionPane.showMessageDialog(this,
                    "Error: " + e.getMessage());
        }
    }// GEN-LAST:event_btnCrearActionPerformed

