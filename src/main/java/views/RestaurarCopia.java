    // metodos
    private void cargarCopias() {

        try {

            jCCopiSeg.removeAllItems();

            Path ruta = new File(
                    "copiaSeguridad",
                    "Hacer Copia Seguridad").toPath();

            Files.list(ruta)
                    .filter(Files::isDirectory)
                    .forEach(carpeta -> jCCopiSeg.addItem(
                            carpeta.getFileName().toString()));

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Error al cargar las copias");
        }
    }

