    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
        try {

            String cantidadTexto = txtCantAportada.getText().trim();

            if (cantidadTexto.isBlank()) {

                JOptionPane.showMessageDialog(this,
                        "Faltan campos por rellenar");

            } else {

                Double cantidadAportada = Double.parseDouble(cantidadTexto);

                Objetivo objetivo = obtenerObjetivoSeleccionado();

                DetalleObjetivoProgramado detalleProg = ServicioDetalleObjetivoProgramado.buscarDetallePorObjetivo(
                        objetivo.getCodObjetivos());

                if (detalleProg.getFechaInactividadDetprog() != null) {

                    throw new IllegalArgumentException(
                            "El objetivo está inactivo");
                }

                Double restante = objetivo.getCantidadObj() - objetivo.getCantConseObj();

                if (cantidadAportada <= 0) {

                    JOptionPane.showMessageDialog(this,
                            "La cantidad debe ser mayor que 0");

                } else if (cantidadAportada > cuenta.getSaldoCuentas()) {

                    JOptionPane.showMessageDialog(this,
                            "No puedes aportar más dinero del que tienes");

                } else if (cantidadAportada > restante) {

                    JOptionPane.showMessageDialog(this,
                            "No puedes aportar más de lo que falta por pagar");

                } else {

                    objetivo.setCantConseObj(
                            objetivo.getCantConseObj() + cantidadAportada);

                    cuenta.setSaldoCuentas(
                            cuenta.getSaldoCuentas() - cantidadAportada);

                    DetalleObjetivoPuntual detallePuntual = new DetalleObjetivoPuntual(
                            cantidadAportada,
                            LocalDateTime.now(),
                            cuenta,
                            objetivo);

                    ServicioDetalleObjetivoPuntual
                            .crearDetalleObjetivoPuntual(detallePuntual);

                    cargarTablaPagoDirecto(anadirColumnasPagoDirecto());

                    if (objetivo.getCantConseObj() >= objetivo.getCantidadObj()) {

                        detalleProg.setFechaInactividadDetprog(
                                LocalDate.now());

                        detalleProg.setCantidadFijaDetprog(0.0);

                        cuenta.setSaldoCuentas(
                                cuenta.getSaldoCuentas()
                                        + objetivo.getCantConseObj());

                        objetivo.setCantConseObj(0.0);

                        ServicioDetalleObjetivoProgramado
                                .actualizarDetalleObjetivoProgramado(detalleProg);
                    }

                    ServicioObjetivo.actualizarObjetivo(objetivo);
                    ServicioCuentaApp.actualizarCuentaApp(cuenta);

                    jLSaldoAct.setText(
                            cuenta.getSaldoCuentas().toString());

                    actualizarCantidadRestante();

                    JOptionPane.showMessageDialog(this,
                            "Pago directo realizado correctamente");

                    this.dispose();
                }
            }

        } catch (NumberFormatException e) {

            JOptionPane.showMessageDialog(this,
                    "Introduce un numero . decimales");

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Ha ocurrido un error inesperado OPD");
        }

    }// GEN-LAST:event_btnAceptarActionPerformed

    // metodos
    private void cargarComboObjetivos() {

        jCObj.removeAllItems();

        listaObjetivos = ServicioObjetivo.buscarObjetivosUsuario(
                usuario.getCodUsuarios());

        for (Objetivo objetivo : listaObjetivos) {

            DetalleObjetivoProgramado detalle = ServicioDetalleObjetivoProgramado.buscarDetallePorObjetivo(
                    objetivo.getCodObjetivos());

            if (detalle.getFechaInactividadDetprog() == null) {

                jCObj.addItem(objetivo.getNombreObj());
            }
        }
    }

    private Objetivo obtenerObjetivoSeleccionado() {

        int posicion = jCObj.getSelectedIndex();

        if (posicion >= 0) {

            return listaObjetivos.get(posicion);

        } else {

            return null;
        }
    }

    private void actualizarCantidadRestante() {

        Objetivo objetivo = obtenerObjetivoSeleccionado();

        if (objetivo != null) {

            Double restante = objetivo.getCantidadObj() - objetivo.getCantConseObj();

            jLCantResto.setText(restante.toString());

        }
    }

    private String[] anadirColumnasPagoDirecto() {

        String[] columnas = {
                "Fecha",
                "Cantidad"
        };

        return columnas;
    }

    private void cargarTablaPagoDirecto(String[] anadirColumnas) {

        try {

            ModeloTabla modelo = new ModeloTabla(anadirColumnas, 0);

            Objetivo objetivo = obtenerObjetivoSeleccionado();

            if (objetivo != null) {

                List<DetalleObjetivoPuntual> lista = ServicioDetalleObjetivoPuntual.buscarDetallesPorObjetivo(
                        objetivo.getCodObjetivos());

                SimpleDateFormat formato = new SimpleDateFormat("yyyy-MM-dd HH:mm:ss");

                for (DetalleObjetivoPuntual detalle : lista) {

                    Object[] fila = {
                            formato.format(detalle.getFechaDetpunt()),
                            detalle.getCantidadDetpunt()
                    };

                    modelo.addRow(fila);
                }
            }

            jTable1.setModel(modelo);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Ha ocurrido un error al cargar la tabla");
        }
    }

