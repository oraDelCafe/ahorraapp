    private void btnAceptarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnAceptarActionPerformed
        // TODO add your handling code here:
        try {

            String cantidadTexto = txtCantAportada.getText().trim();

            if (cantidadTexto.isBlank()) {

                JOptionPane.showMessageDialog(this,
                        "Faltan campos por rellenar");

            } else {

                Double cantidadAportada = Double.parseDouble(cantidadTexto);

                Objetivo objetivo = obtenerObjetivoSeleccionado();

                Double restante = objetivo.getCantidadObj() - objetivo.getCantConseObj();

                if (cantidadAportada <= 0) {

                    JOptionPane.showMessageDialog(this,
                            "La cantidad debe ser mayor que 0");

                } else if (cantidadAportada > cuenta.getSaldoCuentas()) {

                    JOptionPane.showMessageDialog(this,
                            "No puedes aportar más dinero del que tienes");

                } else if (cantidadAportada > restante) {

                    JOptionPane.showMessageDialog(this,
                            "No puedes aportar más de lo que falta por pagar");

                } else {

                    objetivo.setCantConseObj(objetivo.getCantConseObj() + cantidadAportada);

                    cuenta.setSaldoCuentas(cuenta.getSaldoCuentas() - cantidadAportada);

                    ServicioObjetivo.actualizarObjetivo(objetivo);
                    ServicioCuentaApp.actualizarCuentaApp(cuenta);

                    jLSaldoAct.setText(cuenta.getSaldoCuentas().toString());
                    actualizarCantidadRestante();

                    JOptionPane.showMessageDialog(this,
                            "Pago directo realizado correctamente");

                    this.dispose();
                }
            }

        } catch (NumberFormatException nfe) {

            JOptionPane.showMessageDialog(this,
                    "Error: puede ser que metieras , en vez de . OPD ");

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());

        }  catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Ha ocurrido un error inesperado OPD ");
        }
    }// GEN-LAST:event_btnAceptarActionPerformed

    // metodos
    private void cargarComboObjetivos() {

        jCObj.removeAllItems();

        listaObjetivos = ServicioObjetivo.buscarObjetivosUsuario(
                usuario.getCodUsuarios());

        for (Objetivo objetivo : listaObjetivos) {

            jCObj.addItem(objetivo.getNombreObj());
        }
    }

    private Objetivo obtenerObjetivoSeleccionado() {

        int posicion = jCObj.getSelectedIndex();

        if (posicion >= 0) {

            return listaObjetivos.get(posicion);

        } else {

            return null;
        }
    }

    private void actualizarCantidadRestante() {

        Objetivo objetivo = obtenerObjetivoSeleccionado();

        if (objetivo != null) {

            Double restante = objetivo.getCantidadObj() - objetivo.getCantConseObj();

            jLCantResto.setText(restante.toString());
        }
    }

