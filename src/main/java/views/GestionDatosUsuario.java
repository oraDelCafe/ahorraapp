    private void btnModificarActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnModificarActionPerformed
        // TODO add your handling code here:
        try {

            String nombre = txtNombre.getText().trim();
            String ape1 = txtApe1.getText().trim();
            String ape2 = txtApe2.getText().trim();
            String dni = txtDni.getText().trim();
            String direccion = txtDir.getText().trim();
            String telefono = txtTele.getText().trim();
            String email = txtEmail.getText().trim();
            String cuentaBanco = txtCuentaVExt.getText().trim();

            if (nombre.isBlank()|| ape1.isBlank() || ape2.isBlank()
                    || dni.isBlank() || direccion.isBlank() || telefono.isBlank()
                    || email.isBlank() || cuentaBanco.isBlank()) {

                JOptionPane.showMessageDialog(this,
                        "Faltan campos por rellenar");

            } else {

                usuario.setNombreUsu(nombre);
                usuario.setApe1Usu(ape1);
                usuario.setApe2Usu(ape2);
                usuario.setDniUsu(dni);
                usuario.setDirUsu(direccion);
                usuario.setTlfUsu(telefono);
                usuario.setEmailUsu(email);
                // actualiza usuarios.
                ServicioUsuario.actualizarUsuario(usuario);
                // actualiza cuenta
                if (cuenta != null) {

                    cuenta.setCuentaBancoExterna(cuentaBanco);
                    ServicioCuentaApp.actualizarCuentaApp(cuenta);
                } else {
                    JOptionPane.showMessageDialog(this,
                            "Datos modificados correctamente");
                }

                JOptionPane.showMessageDialog(this,
                        "Datos modificados correctamente");

                this.dispose();
            }

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Ha ocurrido un error inesperado GDUM");
        }
    }// GEN-LAST:event_btnModificarActionPerformed

