    private void btnPassActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnPassActionPerformed
        // TODO add your handling code here:
        try {

            int opcion = JOptionPane.showConfirmDialog(this,
                    "¿Seguro que quieres cambiar la contraseña?",
                    "Cambiar contraseña",
                    JOptionPane.YES_NO_OPTION);

            if (opcion == JOptionPane.YES_OPTION) {

                String nuevaPass = JOptionPane.showInputDialog(this,
                        "Introduce la nueva contraseña");

                if (nuevaPass == null || nuevaPass.isBlank()) {

                    throw new IllegalArgumentException(
                            "Debes introducir una contraseña");
                }

                nuevaPass = nuevaPass.trim();

                if (!Usuario.comprobarPass(
                        usuario.getPass(),
                        nuevaPass)) {

                    throw new IllegalArgumentException(
                            "La contraseña debe tener al menos 5 letras seguidas de 2 números y ser distinta de la actual");
                }

                usuario.setPass(nuevaPass);

                ServicioUsuario.actualizarUsuario(usuario);

                jLPass.setText(usuario.getPass());

                JOptionPane.showMessageDialog(this,
                        "Contraseña modificada correctamente");
            }

        } catch (IllegalArgumentException e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Ha ocurrido un error inesperado GDUP");
        }
    }// GEN-LAST:event_btnPassActionPerformed

