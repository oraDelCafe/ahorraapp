        private void btnCrearActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_btnCrearActionPerformed
                // TODO add your handling code here:
                try {

                        String nombre = txtNombre.getText().trim();
                        String descripcion = txtDescripcion.getText().trim();
                        String cantidadTotalTexto = txtCantTotal.getText().trim();
                        String cantidadPeriodoTexto = txtCantM.getText().trim();

                        if (nombre.isBlank() || descripcion.isBlank()
                                        || cantidadTotalTexto.isBlank() || cantidadPeriodoTexto.isBlank()) {

                                JOptionPane.showMessageDialog(this,
                                                "Faltan campos por rellenar");

                        } else {

                                Double cantidadTotal = Double.parseDouble(cantidadTotalTexto);
                                Double cantidadPeriodo = Double.parseDouble(cantidadPeriodoTexto);

                                if (cantidadTotal <= 0 || cantidadPeriodo <= 0) {

                                        throw new IllegalArgumentException(
                                                        "La cantidad periódica debe ser mayor que 0");

                                } else {

                                        LocalDate fechaInicio = LocalDate.parse(txtFechIni.getText());

                                        if (fechaInicio.isBefore(LocalDate.now())) {

                                                throw new IllegalArgumentException(
                                                                "La fecha no puede ser anterior a hoy");
                                        }

                                        TipoPeriodicidad periodo = TipoPeriodicidad
                                                        .valueOf(jCPeriodo.getSelectedItem().toString());

                                        LocalDate fechaFin = calcularFechaFin(
                                                        cantidadTotal,
                                                        cantidadPeriodo,
                                                        periodo);

                                        Objetivo objetivo = new Objetivo(
                                                        nombre,
                                                        cantidadTotal,
                                                        descripcion,
                                                        0.0,
                                                        usuario);

                                        ServicioObjetivo.crearObjetivo(objetivo);

                                        DetalleObjetivoProgramado detalle = new DetalleObjetivoProgramado(
                                                        fechaInicio,
                                                        cantidadPeriodo,
                                                        fechaFin,
                                                        periodo,
                                                        cuentaApp,
                                                        objetivo);

                                        ServicioDetalleObjetivoProgramado.crearDetalleObjetivoProgramado(detalle);

                                        JOptionPane.showMessageDialog(this,
                                                        "Objetivo creado correctamente");

                                        this.dispose();

                                }
                        }

                }catch (NumberFormatException e) {

                        JOptionPane.showMessageDialog(this,
                                        "Introduce un numero . decimales");

                } catch (IllegalArgumentException e) {

                        JOptionPane.showMessageDialog(this,
                                        e.getMessage());

                } catch (Exception e) {

                        JOptionPane.showMessageDialog(this,
                                        "Ha ocurrido un error inesperado OC");
                }

        }// GEN-LAST:event_btnCrearActionPerformed

        // metodos
        private LocalDate calcularFechaFin(Double cantidadTotal, Double cantidadPeriodo, TipoPeriodicidad periodo) {

                int unidades = (int) Math.ceil(cantidadTotal / cantidadPeriodo);

                LocalDate fechaFin = LocalDate.now();

                if (null != periodo) {
                        switch (periodo) {
                                case diario -> fechaFin = fechaFin.plusDays(unidades);
                                case quicena -> fechaFin = fechaFin.plusDays(unidades * 15);
                                case mensual -> fechaFin = fechaFin.plusMonths(unidades);
                                case trimestral -> fechaFin = fechaFin.plusMonths(unidades * 3);
                        }
                }
                return fechaFin;
        }

        private void cargarDatosPeriodo() {
                jCPeriodo.removeAllItems();

                for (TipoPeriodicidad tipo : TipoPeriodicidad.values()) {
                        jCPeriodo.addItem(tipo.toString());
                }
        }

