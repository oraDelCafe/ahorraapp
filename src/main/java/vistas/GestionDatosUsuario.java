    private void cargarDatosUsuario() {

        try {
            // datos actuales
            jLNombre.setText(usuario.getNombreUsu());
            jLApe1.setText(usuario.getApe1Usu());
            jLApe2.setText(usuario.getApe2Usu());
            jLDni.setText(usuario.getDniUsu());
            jLDir.setText(usuario.getDirUsu());
            jLTele.setText(usuario.getTlfUsu());
            jLEmail.setText(usuario.getEmailUsu());
            jLPass.setText(usuario.getPass());

            // relleno con datos actuales para cambiar solo el necesario.
            txtNombre.setText(usuario.getNombreUsu());
            txtApe1.setText(usuario.getApe1Usu());
            txtApe2.setText(usuario.getApe2Usu());
            txtDni.setText(usuario.getDniUsu());
            txtDir.setText(usuario.getDirUsu());
            txtTele.setText(usuario.getTlfUsu());
            txtEmail.setText(usuario.getEmailUsu());
            txtPass.setText(usuario.getPass());

            cuentaApp = ServicioCuentaApp.buscarCuentaUsuario(
                    usuario.getCodUsuarios());

            if (cuentaApp != null) {

                jLCuentaVExt.setText(cuentaApp.getCuentaBancoExterna());
                txtCuentaVExt.setText(cuentaApp.getCuentaBancoExterna());

            } else {

                jLCuentaVExt.setText("Sin cuenta");
                txtCuentaVExt.setText("");
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    "Error: " + e.getMessage());
        }
    }

